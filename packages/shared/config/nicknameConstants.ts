const generateThreeDigitNumber = (): string => {
  const num = Math.floor(Math.random() * 1000); // 0 to 999
  return num.toString().padStart(3, '0'); // "001", "023", "999"
};

const generateEngNickname = (): string => {
  const numbers = NumberDictionary.generate({ min: 0, max: 999 });

  return uniqueNamesGenerator({
    dictionaries: [adjectives, animals, numbers],
    separator: '',
    style: 'capital',
    length: 3,
  }); // e.g., "MajesticTiger007"
};

const generateKorNickname = (): string => {
  const adjective = koreanAdjectives[Math.floor(Math.random() * koreanAdjectives.length)];
  const noun = koreanNouns[Math.floor(Math.random() * koreanNouns.length)];
  const number = generateThreeDigitNumber();

  return `${adjective}${noun}${number}`;
};

export const generateNickName = (langCode: LangCode) => {
  switch (langCode) {
    case 'kor':
      return generateKorNickname();
    case 'eng':
      return generateEngNickname();
    default:
      return generateEngNickname();
  }
};
